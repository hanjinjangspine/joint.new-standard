export function patientGuideHref(guide: PatientGuide) {
  return `/patient-guides/${guide.slug}`;
}

export function getPatientGuide(slug: string) {
  return patientGuides.find((guide) => guide.slug === slug);
}

export function getPatientGuides(ids?: string[]) {
  if (!ids) return patientGuides;
  const idSet = new Set(ids);
  return patientGuides.filter((guide) => idSet.has(guide.id));
}
